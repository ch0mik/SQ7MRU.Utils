using System.Globalization;
using System.Text;

namespace SQ7MRU.Utils;

/// <summary>Writes ADI using a current-standard or explicit provider-compatibility profile.</summary>
public static class AdifWriter
{
    /// <summary>Gets the reviewed protocol revision, independent of the product release version.</summary>
    public static string SupportedRevision => AdifMetadata.Revision;

    /// <summary>Writes a document without silently changing its declared ADIF revision or field values.</summary>
    /// <param name="document">Document whose populated header receives a valid readable prefix and EOH.</param>
    /// <param name="profile">Standard enforces reviewed export restrictions; EqslLegacy preserves older/provider data without a current-conformance claim.</param>
    /// <param name="cancellationToken">Cancels validation and construction without returning partial output.</param>
    /// <returns>ADI with invariant lengths, CRLF formatting and terminated records.</returns>
    /// <exception cref="ArgumentNullException">The document is null.</exception>
    /// <exception cref="FormatException">Content is invalid for the profile or exceeds limits.</exception>
    /// <exception cref="ArgumentOutOfRangeException">The profile is unknown.</exception>
    /// <exception cref="OperationCanceledException">Cancellation is requested.</exception>
    /// <remarks>Standard export rejects international/import-only data instead of dropping it. Export of an older declared revision requires explicit EqslLegacy selection. Limits: 32 MiB characters, 100,000 fields total, 4,096 per header/record. ADX is unsupported.</remarks>
    public static string Export(AdifDocument document, AdifProfile profile = AdifProfile.Standard, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(document);
        cancellationToken.ThrowIfCancellationRequested();
        var fields = (long)document.Header.Count + document.Records.Sum(r => (long)r.Fields.Count);
        if (fields > 100_000 || document.Header.Count > 4096 || document.Records.Any(r => r.Fields.Count > 4096))
            throw new FormatException("ADIF field-count limit exceeded.");
        AdifValidation.Document(document, profile, exporting: true, cancellationToken);
        var builder = new StringBuilder();
        if (document.Header.Count > 0)
        {
            builder.Append("Generated by SQ7MRU.Utils\r\n");
            foreach (var field in document.Header) Append(field);
            builder.Append("<EOH>\r\n");
        }
        foreach (var record in document.Records)
        {
            cancellationToken.ThrowIfCancellationRequested();
            foreach (var field in record.Fields) Append(field);
            builder.Append("<EOR>\r\n");
        }
        if (builder.Length > 32 * 1024 * 1024) throw new FormatException("ADIF output exceeds the character limit.");
        return builder.ToString();

        void Append(AdifField field)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if ((long)builder.Length + field.Value.Length + field.Name.Length + 32 > 32 * 1024 * 1024)
                throw new FormatException("ADIF output exceeds the character limit.");
            builder.Append('<').Append(field.Name).Append(':').Append(field.Value.Length.ToString(CultureInfo.InvariantCulture));
            if (field.TypeIndicator is not null) builder.Append(':').Append(field.TypeIndicator);
            builder.Append('>').Append(field.Value).Append(' ');
        }
    }
}
